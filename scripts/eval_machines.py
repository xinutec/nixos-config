#!/usr/bin/env python3
"""Evaluate every machine's complete NixOS configuration.

This is the real check in this repository's gate. Evaluating a machine runs the
module system, agenix and home-manager over every option definition, which is
what catches a removed package, a renamed option or a typo'd attribute — the
class of breakage you otherwise discover halfway through a `nixos-rebuild switch`
on the host. It evaluates only; nothing is built, so it runs on the Mac.

Two things a host has that a clean checkout does not, both reconstructed here:

    configuration.nix           generated by setup.sh from configuration.nix.dist
    hardware-configuration.nix  the machine's own, at the repo ROOT, because
                                base-configuration imports it relative to itself

Both are gitignored because they are per-host; the per-machine hardware files ARE
tracked, so the layout is reproducible — pick the machine's, drop it at the root.

The password is a dummy. setup.sh interpolates a real hash from `mkpasswd`; the
eval only needs the option to typecheck as a string, so no secret is involved.

NIX_PATH (nixpkgs + home-manager) comes from the devshell in `nix/flake.nix`, not
from `-I` flags here, so a manual eval from an interactive shell resolves exactly
what the gate does. The machines are still channel-based in production; pinning
here only makes the GATE reproducible, and it is why amun's EOL k3s pin shows up
as a failure rather than as a property of whichever channel the checking machine
happens to have.

Every machine is evaluated even after one fails, and the failures are named at
the end: a gate that stops at the first reports one machine when three are
broken. Was the `for machine in machines/*/` loop in scripts/verify.sh.
"""

from __future__ import annotations

import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

# All three machines are x86_64 Linux, and this usually runs from an aarch64 Mac,
# so the system has to be named rather than inferred from the host.
SYSTEM = "x86_64-linux"

DUMMY_PASSWD = "$6$dummy$dummy"

ROOT = Path(__file__).resolve().parent.parent

STORE_PATH = re.compile(r"/nix/store/\S*\.drv")


def machines() -> list[str]:
    return sorted(p.name for p in (ROOT / "machines").iterdir() if p.is_dir())


def stage(work: Path, machine: str) -> None:
    """Put the two per-host files a checkout lacks where the modules expect them."""
    dist = (ROOT / "configuration.nix.dist").read_text()
    configuration = dist.replace("@HOST@", machine).replace("@PASSWD@", DUMMY_PASSWD)
    (work / "configuration.nix").write_text(configuration)
    shutil.copyfile(
        ROOT / "machines" / machine / "hardware-configuration.nix",
        work / "hardware-configuration.nix",
    )


def evaluate(work: Path) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [
            "nix-instantiate",
            "<nixpkgs/nixos>",
            "-A",
            "system",
            "-I",
            f"nixos-config={work / 'configuration.nix'}",
            "--argstr",
            "system",
            SYSTEM,
        ],
        capture_output=True,
        text=True,
        check=False,
    )


def main() -> int:
    broken: list[str] = []
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp) / "tree"
        # The eval reads the whole tree, so it gets a copy without the git
        # metadata rather than the working directory itself — nothing here should
        # be able to write into the repository.
        shutil.copytree(ROOT, work, ignore=shutil.ignore_patterns(".git"))

        for machine in machines():
            stage(work, machine)
            result = evaluate(work)
            if result.returncode == 0:
                found = STORE_PATH.search(result.stdout)
                print(f"  ok   {machine:<6} {found.group(0) if found else ''}")
            else:
                broken.append(machine)
                print(f"  FAIL {machine:<6} does not evaluate")
                errors = [
                    line for line in result.stderr.splitlines() if "error:" in line
                ]
                for line in errors[:5]:
                    print(f"         {line}")

    if broken:
        print(f"machines that do not evaluate: {', '.join(broken)}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
